// site-generator-speed-01: a faster drop-in for makefun-site 1.0.0.
// Written from the reference's README and behaviour, as an original single-pass
// implementation. It returns exactly makefun-site 1.0.0's answer for every input:
// same output tree, byte for byte. No dependencies, ES module, no I/O, no clock,
// no randomness. Optimisations, all semantics-preserving:
//  - one pass over each source's lines (no lex-token array, no body re-join),
//  - bulk plain-run escaping in the inline renderer (no per-character loop),
//  - ASCII fast path + cache for slugify, cached cards and word counts,
//  - templates parsed once per distinct source, rendered with reused scopes.

const REPORT_FILE = 'build-report.txt';
const RESERVED = ['posts', 'tags', 'page'];
const SLUG_MAX = 64;
const INCLUDE_DEPTH = 8;

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const ESC_RE = /[&<>"']/g;
const NON_ASCII = /[^\x00-\x7F]/;

export function escapeHtml(text) {
  ESC_RE.lastIndex = 0;
  let m = ESC_RE.exec(text);
  if (m === null) return text;
  let out = '';
  let last = 0;
  do {
    out += text.slice(last, m.index) + ESCAPES[m[0]];
    last = m.index + 1;
  } while ((m = ESC_RE.exec(text)) !== null);
  return out + text.slice(last);
}

const slugCache = new Map();

export function slugify(text) {
  const hit = slugCache.get(text);
  if (hit !== undefined) return hit;
  const plain = NON_ASCII.test(text) ? text.normalize('NFKD').replace(/\p{M}/gu, '') : text;
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const ch = plain[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  out = out.slice(0, SLUG_MAX).replace(/-+$/, '');
  const slug = out === '' ? 'untitled' : out;
  slugCache.set(text, slug);
  return slug;
}

export function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export function longDate(date) {
  const y = date.slice(0, 4);
  const m = Number(date.slice(5, 7));
  const d = Number(date.slice(8, 10));
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

// ---------------------------------------------------------------- front matter

const KEYS = ['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary'];
const LINE = /^([a-z_]+):(?: (.*))?$/;
const DATE = /^(\d{4})-(\d{2})-(\d{2})$/;
const NAME = /^[a-z0-9-]+$/;
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const TAG = /^[^"[\]]+$/;
const BLANK = /^[ \t]*$/;

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

function stringOf(raw) {
  if (raw.charCodeAt(0) === 34) {
    if (raw.length < 2 || raw.charCodeAt(raw.length - 1) !== 34) return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw.charCodeAt(0) === 91) return { error: 'a bare string opens on [' };
  return { value: raw };
}

function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      const m = DATE.exec(raw);
      const y = m ? Number(m[1]) : 0;
      const mo = m ? Number(m[2]) : 0;
      const d = m ? Number(m[3]) : 0;
      if (!m || y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (raw.charCodeAt(0) !== 91 || raw.charCodeAt(raw.length - 1) !== 93) return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',').map((t) => t.trim());
      if (tags.some((t) => t === '' || !TAG.test(t))) return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout':
      return NAME.test(raw) ? { value: raw } : { error: 'key "layout": not a template name' };
    case 'slug':
      return SLUG.test(raw) && raw.length <= 64 ? { value: raw } : { error: 'key "slug": not a slug' };
    default:
      return { error: `unknown key "${key}"` };
  }
}

// `lines` is the source's text split on '\n'. Returns { data, bodyStart } (the
// body is lines[bodyStart..]) or { error }.
export function parseFrontMatter(lines) {
  if (lines[0] !== '---') return { error: 'no front matter' };
  let close = -1;
  for (let i = 1; i < lines.length; i++) {
    if (lines[i] === '---') {
      close = i;
      break;
    }
  }
  if (close === -1) return { error: 'the front matter is not closed' };
  const data = {};
  for (let i = 1; i < close; i++) {
    const line = lines[i];
    if (BLANK.test(line) || line.charCodeAt(0) === 35) continue;
    const m = LINE.exec(line);
    if (!m) return { error: `line ${i + 1} is not "key: value"` };
    const key = m[1];
    const raw = (m[2] ?? '').replace(/[ \t]+$/, '');
    if (!KEYS.includes(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
  }
  if (!Object.hasOwn(data, 'title')) return { error: 'no title' };
  return { data, bodyStart: close + 1 };
}

// ---------------------------------------------------------------- markdown

const FENCE_OPEN = /^```([A-Za-z0-9_+-]*)[ \t]*$/;
const FENCE_CLOSE = /^```[ \t]*$/;
const HEADING = /^(#{1,6})[ \t]+(.*?)[ \t]*$/;
const HR = /^(?:---|\*\*\*)[ \t]*$/;
const BULLET = /^[-*] (.*)$/;
const ORDERED = /^(\d{1,9})\. (.*)$/;
const CONTINUED = /^ {2,}\S/;

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);
const SPECIAL_RE = /[\\`*[]/g;

/** `line` with spaces and tabs at either end dropped. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

function headingOf(line) {
  const m = HEADING.exec(line);
  return m === null || m[2] === '' ? null : { depth: m[1].length, text: m[2] };
}

// Whether `line` ends a paragraph: a blank line, a fence, a heading or a break.
function endsParagraph(line) {
  if (line === '' || line.charCodeAt(0) === 32 || line.charCodeAt(0) === 9) return BLANK.test(line);
  const c = line.charCodeAt(0);
  if (c === 96) return FENCE_OPEN.test(line);
  if (c === 35) return headingOf(line) !== null;
  if (c === 45 || c === 42) return HR.test(line);
  return false;
}

// Block kind of a line at a block start: 'blank' | 'fence' | 'heading' | 'hr' |
// 'quote' | 'bullet' | 'ordered' | 'para'. Equivalent to the reference's ordered
// regex tests, dispatched on the first character.
function blockKind(line) {
  if (line === '') return 'blank';
  const c = line.charCodeAt(0);
  if (c === 32 || c === 9) return BLANK.test(line) ? 'blank' : 'para';
  if (c === 96) {
    const f = FENCE_OPEN.exec(line);
    return f === null ? 'para' : 'fence';
  }
  if (c === 35) return headingOf(line) === null ? 'para' : 'heading';
  if (c === 45) {
    if (HR.test(line)) return 'hr';
    return BULLET.test(line) ? 'bullet' : 'para';
  }
  if (c === 42) {
    if (HR.test(line)) return 'hr';
    return BULLET.test(line) ? 'bullet' : 'para';
  }
  if (c === 62) return 'quote';
  if (c >= 48 && c <= 57) return ORDERED.test(line) ? 'ordered' : 'para';
  return 'para';
}

// The first index >= `from` where `s` holds `what` outside a backslash escape,
// or -1. Equivalent to the reference's scan, but found with indexOf plus a
// backslash-parity check (only backslashes at or after `from` count).
function findUnescaped(s, what, from) {
  let j = s.indexOf(what, from);
  while (j !== -1) {
    let k = j - 1;
    let bs = 0;
    while (k >= from && s.charCodeAt(k) === 92) {
      bs++;
      k--;
    }
    if ((bs & 1) === 0) return j;
    j = s.indexOf(what, j + 1);
  }
  return -1;
}

// The first single * from `from` (one whose run is not **), outside an escape.
function findSingleStar(s, from) {
  let j = s.indexOf('*', from);
  while (j !== -1) {
    let k = j - 1;
    let bs = 0;
    while (k >= from && s.charCodeAt(k) === 92) {
      bs++;
      k--;
    }
    if ((bs & 1) === 1) {
      j = s.indexOf('*', j + 1);
      continue;
    }
    if (s.charCodeAt(j + 1) === 42) {
      j = s.indexOf('*', j + 2);
      continue;
    }
    return j;
  }
  return -1;
}

// Index of the next inline special character at or after `i`, or -1.
// One Irregexp pass (lastIndex is set fresh on every call, so the recursion
// in inline() cannot clobber it).
function nextSpecial(s, i) {
  SPECIAL_RE.lastIndex = i;
  const m = SPECIAL_RE.exec(s);
  return m === null ? -1 : m.index;
}

/** `s` rendered inline; `env.link(target)` is a link's href. */
export function inline(s, env) {
  const n = s.length;
  let out = '';
  let i = 0;
  let plain = 0;
  while (true) {
    const k = nextSpecial(s, i);
    if (k === -1) break;
    const c = s.charCodeAt(k);
    if (c === 92) {
      // Backslash: an escapable next character is written escaped, else the
      // backslash stays in the plain run (it is not an escape character).
      if (k + 1 < n && ESCAPABLE.has(s[k + 1])) {
        if (k > plain) out += escapeHtml(s.slice(plain, k));
        out += escapeHtml(s[k + 1]);
        i = k + 2;
        plain = i;
      } else {
        i = k + 1;
      }
      continue;
    }
    if (c === 96) {
      const j = s.indexOf('`', k + 1);
      if (j > k + 1) {
        if (k > plain) out += escapeHtml(s.slice(plain, k));
        out += `<code>${escapeHtml(s.slice(k + 1, j))}</code>`;
        i = j + 1;
        plain = i;
      } else {
        i = k + 1;
      }
      continue;
    }
    if (c === 42) {
      if (s.charCodeAt(k + 1) === 42) {
        const j = findUnescaped(s, '**', k + 2);
        if (j > k + 2) {
          if (k > plain) out += escapeHtml(s.slice(plain, k));
          out += `<strong>${inline(s.slice(k + 2, j), env)}</strong>`;
          i = j + 2;
          plain = i;
        } else {
          i = k + 2;
        }
        continue;
      }
      const j = findSingleStar(s, k + 1);
      if (j > k + 1) {
        if (k > plain) out += escapeHtml(s.slice(plain, k));
        out += `<em>${inline(s.slice(k + 1, j), env)}</em>`;
        i = j + 1;
        plain = i;
      } else {
        i = k + 1;
      }
      continue;
    }
    // '[': a link when a ']' closes the text, '(' follows at once, and the
    // next ')' closes a non-empty target with no whitespace.
    const close = findUnescaped(s, ']', k + 1);
    const m = close !== -1 && s.charCodeAt(close + 1) === 40 ? s.indexOf(')', close + 2) : -1;
    const target = m === -1 ? '' : s.slice(close + 2, m);
    if (target !== '' && !/\s/.test(target)) {
      if (k > plain) out += escapeHtml(s.slice(plain, k));
      out += `<a href="${escapeHtml(env.link(target))}">${inline(s.slice(k + 1, close), env)}</a>`;
      i = m + 1;
      plain = i;
    } else {
      i = k + 1;
    }
  }
  if (n > plain) out += escapeHtml(s.slice(plain, n));
  return out;
}

/**
 * The body lines rendered: its HTML (each block on its own lines, a "\n" after
 * the last), its table of contents (every level 2 and 3 heading) and its
 * excerpt (the first paragraph's inline HTML, or ""). `wordCount` is the body's
 * word count (runs of non-whitespace), counted here while the lines are in hand.
 */
export function renderMarkdown(lines, start, env) {
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  // The body's word count (runs of non-whitespace; '\n' never joins runs
  // across lines), counted in one pass before the blocks are read.
  const words = wordsOfLines(lines, start);
  let i = start;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    const kind = blockKind(line);
    if (kind === 'blank') {
      i++;
      continue;
    }
    if (kind === 'fence') {
      const fence = FENCE_OPEN.exec(line);
      const body = [];
      i++;
      while (i < n && !FENCE_CLOSE.test(lines[i])) body.push(lines[i++]);
      i++;
      const cls = fence[1] === '' ? '' : ` class="language-${escapeHtml(fence[1])}"`;
      blocks.push(`<pre><code${cls}>${body.length === 0 ? '' : `${escapeHtml(body.join('\n'))}\n`}</code></pre>\n`);
      continue;
    }
    if (kind === 'heading') {
      const h = headingOf(line);
      const id = uniqueSlug(slugify(h.text), ids);
      const html = inline(h.text, env);
      blocks.push(`<h${h.depth} id="${id}">${html}</h${h.depth}>\n`);
      if (h.depth === 2 || h.depth === 3) toc.push({ level: h.depth, id, html });
      i++;
      continue;
    }
    if (kind === 'hr') {
      blocks.push('<hr>\n');
      i++;
      continue;
    }
    if (kind === 'quote') {
      let text = '';
      let first = true;
      while (i < n && lines[i].charCodeAt(0) === 62) {
        const l = trimLine(lines[i++].replace(/^> ?/, ''));
        if (l === '') continue;
        if (first) {
          text = l;
          first = false;
        } else text += `\n${l}`;
      }
      blocks.push(first ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(text, env)}</p>\n</blockquote>\n`);
      continue;
    }
    if (kind === 'bullet' || kind === 'ordered') {
      const isOrdered = kind === 'ordered';
      const marker = isOrdered ? ORDERED : BULLET;
      const items = [];
      let startNum = 1;
      if (isOrdered) startNum = Number(ORDERED.exec(line)[1]);
      while (i < n) {
        const mm = marker.exec(lines[i]);
        if (mm !== null) {
          items.push(trimLine(isOrdered ? mm[2] : mm[1]));
          i++;
        } else if (CONTINUED.test(lines[i])) {
          items[items.length - 1] += `\n${trimLine(lines[i])}`;
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && startNum !== 1 ? `<ol start="${startNum}">` : `<${tag}>`;
      let html = `${open}\n`;
      for (const item of items) html += `<li>${inline(item, env)}</li>\n`;
      blocks.push(`${html}</${tag}>\n`);
      continue;
    }
    // Paragraph: lines up to a blank line, a fence, a heading or a break.
    let text = trimLine(line);
    i++;
    while (i < n && !endsParagraph(lines[i])) {
      text += `\n${trimLine(lines[i])}`;
      i++;
    }
    const html = inline(text, env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>\n`);
  }
  return { html: blocks.join(''), toc, excerpt: excerpt ?? '', words };
}

